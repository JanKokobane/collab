export function enhanceInputsWithIcons(container: HTMLElement | Document | null = document) {
  if (!container) return;
  const elements = container.querySelectorAll<HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement>(
    'input:not([type="checkbox"]):not([type="radio"]):not([type="file"]):not([type="hidden"]):not([type="color"]):not([type="button"]):not([type="submit"]):not([type="reset"]), select, textarea'
  );

  elements.forEach((el) => {
    if (
      el.closest('.input-with-icon') ||
      el.closest('.search') ||
      el.closest('.no-input-icon') ||
      el.dataset.iconEnhanced === 'true'
    ) {
      return;
    }
    el.dataset.iconEnhanced = 'true';
  });
}
